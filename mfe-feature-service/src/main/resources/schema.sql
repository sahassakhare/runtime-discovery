-- Application Schema
CREATE TABLE IF NOT EXISTS MICROFRONTEND (
  ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
  NAME                VARCHAR(255) NOT NULL UNIQUE,
  DESCRIPTION         VARCHAR(255),
  TYPE                VARCHAR(255),
  FEATURE_GROUP_NAME  VARCHAR(255),
  CREATED_AT          TIMESTAMP,
  UPDATED_AT          TIMESTAMP,
  PRIMARY KEY(ID)
);

CREATE TABLE IF NOT EXISTS VERSION (
  ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
  VERSION             VARCHAR(255) NOT NULL,
  REMOTE_ENTRY        VARCHAR(255) NOT NULL,
  INTEGRITY           VARCHAR(255),
  ACTIVE              BOOLEAN NOT NULL,
  RELEASE_TRACK       VARCHAR(255), -- STABLE, CANARY, BETA
  MICROFRONTEND_ID    BIGINT,
  CREATED_AT          TIMESTAMP,
  PRIMARY KEY(ID),
  FOREIGN KEY(MICROFRONTEND_ID) REFERENCES MICROFRONTEND(ID)
);

-- FF4j Schema for 1.8.x
CREATE TABLE IF NOT EXISTS FF4J_FEATURES (
  FEAT_UID     VARCHAR(100),
  ENABLE       INTEGER,
  DESCRIPTION  VARCHAR(255),
  STRATEGY     VARCHAR(255),
  EXPRESSION   VARCHAR(255),
  GROUPNAME    VARCHAR(100),
  PRIMARY KEY(FEAT_UID)
);

CREATE TABLE IF NOT EXISTS FF4J_ROLES (
  FEAT_UID     VARCHAR(100),
  ROLE_NAME    VARCHAR(100),
  PRIMARY KEY(FEAT_UID, ROLE_NAME),
  FOREIGN KEY(FEAT_UID) REFERENCES FF4J_FEATURES(FEAT_UID)
);

CREATE TABLE IF NOT EXISTS FF4J_CUSTOM_PROPERTIES (
  PROPERTY_ID  VARCHAR(100),
  CLAZZ        VARCHAR(255),
  CURRENTVALUE VARCHAR(255),
  FIXEDVALUES  VARCHAR(1000),
  DESCRIPTION  VARCHAR(255),
  FEAT_UID     VARCHAR(100),
  PRIMARY KEY(PROPERTY_ID, FEAT_UID),
  FOREIGN KEY(FEAT_UID) REFERENCES FF4J_FEATURES(FEAT_UID)
);

CREATE TABLE IF NOT EXISTS FF4J_PROPERTIES (
  PROPERTY_ID  VARCHAR(100),
  CLAZZ        VARCHAR(255),
  CURRENTVALUE VARCHAR(255),
  FIXEDVALUES  VARCHAR(1000),
  DESCRIPTION  VARCHAR(255),
  PRIMARY KEY(PROPERTY_ID)
);

CREATE TABLE IF NOT EXISTS FF4J_AUDIT (
  EVT_UUID     VARCHAR(100),
  EVT_TIME     TIMESTAMP,
  EVT_TYPE     VARCHAR(100),
  EVT_NAME     VARCHAR(100),
  EVT_ACTION   VARCHAR(100),
  EVT_HOSTNAME VARCHAR(100),
  EVT_SOURCE   VARCHAR(100),
  EVT_DURATION INTEGER,
  EVT_USER     VARCHAR(100),
  EVT_VALUE    VARCHAR(100),
  EVT_KEYS     VARCHAR(255),
  PRIMARY KEY(EVT_UUID)
);
