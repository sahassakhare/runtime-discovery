-- Application Schema
CREATE TABLE IF NOT EXISTS TENANT (
  ID                  VARCHAR(255) NOT NULL,
  NAME                VARCHAR(255) NOT NULL,
  CONTACT_EMAIL       VARCHAR(255),
  ACTIVE              BOOLEAN DEFAULT TRUE,
  CREATED_AT          TIMESTAMP,
  UPDATED_AT          TIMESTAMP,
  PRIMARY KEY(ID)
);

CREATE TABLE IF NOT EXISTS MFE_APPLICATION_GROUP (
  GROUP_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR(255) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS MFE_APPLICATIONS (
  APP_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR(255) NOT NULL,
  GROUP_ID BIGINT NOT NULL,
  TAGS VARCHAR(255),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_MFE_APPLICATIONS_GROUP FOREIGN KEY (GROUP_ID) REFERENCES MFE_APPLICATION_GROUP (GROUP_ID)
);

CREATE TABLE IF NOT EXISTS MFE_APPLICATION_VERSIONS (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  APP_ID BIGINT NOT NULL,
  VERSION VARCHAR(50),
  REGISTERED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  ENVIRONMENT VARCHAR(50) DEFAULT 'Development',
  LATEST BOOLEAN DEFAULT FALSE,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_MFE_APP_VERSIONS_APP FOREIGN KEY (APP_ID) REFERENCES MFE_APPLICATIONS (APP_ID)
);

CREATE TABLE IF NOT EXISTS MFE_SHARED_MODULES (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  APP_VERSION_ID BIGINT NOT NULL,
  NAME VARCHAR(255) NOT NULL,
  LOCATION VARCHAR(255) NOT NULL,
  VERSION VARCHAR(255),
  CONSTRAINT FK_MFE_SHARED_MODULES_APP_VERSION FOREIGN KEY (APP_VERSION_ID) REFERENCES MFE_APPLICATION_VERSIONS (ID)
);

CREATE TABLE IF NOT EXISTS MFE_MICROFRONTEND_HEALTH (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  APP_VERSION_ID BIGINT NOT NULL,
  URL VARCHAR(255),
  STATUS INTEGER NOT NULL,
  LAST_UPTIME TIMESTAMP NOT NULL,
  LAST_DOWNTIME TIMESTAMP,
  CONSTRAINT FK_MFE_MFE_HEALTH_APP_VERSION FOREIGN KEY (APP_VERSION_ID) REFERENCES MFE_APPLICATION_VERSIONS (ID)
);

CREATE TABLE IF NOT EXISTS MFE_DEPENDENCIES (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  APP_VERSION_ID BIGINT NOT NULL,
  NAME VARCHAR(255) NOT NULL,
  VERSION VARCHAR(255) NOT NULL,
  DEP_TYPE VARCHAR(255) NOT NULL,
  CONSTRAINT FK_MFE_DEPENDENCIES_APP_VERSION FOREIGN KEY (APP_VERSION_ID) REFERENCES MFE_APPLICATION_VERSIONS (ID)
);

CREATE TABLE IF NOT EXISTS MFE_EXPOSED_MODULES (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  APP_VERSION_ID BIGINT NOT NULL,
  NAME VARCHAR(255) NOT NULL,
  FILE_PATH VARCHAR(255) NOT NULL,
  CONSTRAINT FK_MFE_EXPOSED_MODULES_APP_VERSION FOREIGN KEY (APP_VERSION_ID) REFERENCES MFE_APPLICATION_VERSIONS (ID)
);

CREATE TABLE IF NOT EXISTS MFE_METADATA (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  APP_VERSION_ID BIGINT NOT NULL,
  NAME VARCHAR(255) NOT NULL,
  META_VALUE VARCHAR(255) NOT NULL,
  CONSTRAINT FK_MFE_METADATA_APP_VERSION FOREIGN KEY (APP_VERSION_ID) REFERENCES MFE_APPLICATION_VERSIONS (ID)
);

CREATE TABLE IF NOT EXISTS MFE_CONSUMED_REMOTES (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CONSUMER_VERSION_ID BIGINT NOT NULL,
  REMOTE_NAME VARCHAR(255) NOT NULL,
  USED_MODULES VARCHAR(255),
  IS_DYNAMIC BOOLEAN DEFAULT FALSE,
  ENVIRONMENT VARCHAR(50),
  CONSTRAINT FK_MFE_CONSUMED_REMOTES_VERSION FOREIGN KEY (CONSUMER_VERSION_ID) REFERENCES MFE_APPLICATION_VERSIONS (ID)
);

CREATE TABLE IF NOT EXISTS DEPLOYMENT (
  ID          BIGINT GENERATED BY DEFAULT AS IDENTITY,
  VERSION_ID  BIGINT NOT NULL,
  ENVIRONMENT VARCHAR(255) NOT NULL,
  TENANT_ID   VARCHAR(255),
  ACTIVE      BOOLEAN DEFAULT FALSE,
  WEIGHT      INTEGER DEFAULT 100,
  CREATED_AT  TIMESTAMP,
  UPDATED_AT  TIMESTAMP,
  PRIMARY KEY(ID),
  FOREIGN KEY(VERSION_ID) REFERENCES MFE_APPLICATION_VERSIONS(ID)
);


-- FF4j Schema for 1.8.x
CREATE TABLE IF NOT EXISTS FF4J_FEATURES (
  FEAT_UID     VARCHAR(100),
  ENABLE       INTEGER,
  DESCRIPTION  VARCHAR(255),
  STRATEGY     VARCHAR(255),
  EXPRESSION   VARCHAR(255),
  GROUPNAME    VARCHAR(100),
  PRIMARY KEY(FEAT_UID)
);

CREATE TABLE IF NOT EXISTS FF4J_ROLES (
  FEAT_UID     VARCHAR(100),
  ROLE_NAME    VARCHAR(100),
  PRIMARY KEY(FEAT_UID, ROLE_NAME),
  FOREIGN KEY(FEAT_UID) REFERENCES FF4J_FEATURES(FEAT_UID)
);

CREATE TABLE IF NOT EXISTS FF4J_CUSTOM_PROPERTIES (
  PROPERTY_ID  VARCHAR(100),
  CLAZZ        VARCHAR(255),
  CURRENTVALUE VARCHAR(255),
  FIXEDVALUES  VARCHAR(1000),
  DESCRIPTION  VARCHAR(255),
  FEAT_UID     VARCHAR(100),
  PRIMARY KEY(PROPERTY_ID, FEAT_UID),
  FOREIGN KEY(FEAT_UID) REFERENCES FF4J_FEATURES(FEAT_UID)
);

CREATE TABLE IF NOT EXISTS FF4J_PROPERTIES (
  PROPERTY_ID  VARCHAR(100),
  CLAZZ        VARCHAR(255),
  CURRENTVALUE VARCHAR(255),
  FIXEDVALUES  VARCHAR(1000),
  DESCRIPTION  VARCHAR(255),
  PRIMARY KEY(PROPERTY_ID)
);

CREATE TABLE IF NOT EXISTS FF4J_AUDIT (
  EVT_UUID     VARCHAR(100),
  EVT_TIME     TIMESTAMP,
  EVT_TYPE     VARCHAR(100),
  EVT_NAME     VARCHAR(100),
  EVT_ACTION   VARCHAR(100),
  EVT_HOSTNAME VARCHAR(100),
  EVT_SOURCE   VARCHAR(100),
  EVT_DURATION INTEGER,
  EVT_USER     VARCHAR(100),
  EVT_VALUE    VARCHAR(100),
  EVT_KEYS     VARCHAR(255),
  PRIMARY KEY(EVT_UUID)
);
